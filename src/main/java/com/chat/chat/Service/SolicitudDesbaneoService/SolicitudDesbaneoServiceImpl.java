    private String sanitizeAttachmentFileName(String nombreArchivo) {
        String safe = trimToNullable(nombreArchivo, MAX_ATTACHMENT_FILE_NAME_LENGTH);
        if (!hasText(safe)) {
            return "reporte-app";
        }
        safe = safe.replace('\\', '_').replace('/', '_');
        safe = safe.replaceAll("[\\r\\n\\t\\x00-\\x1F\\x7F]+", "_");
        safe = safe.replaceAll("[^A-Za-z0-9._ -]", "_");
        safe = safe.trim();
        if (safe.isBlank()) {
            return "reporte-app";
        }
        return safe.length() > MAX_ATTACHMENT_FILE_NAME_LENGTH
                ? safe.substring(0, MAX_ATTACHMENT_FILE_NAME_LENGTH)
                : safe;
    }

