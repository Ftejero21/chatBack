    private void registrarHistorialCambioEstado(String requestId,
                                                SolicitudDesbaneoEntity entity,
                                                SolicitudDesbaneoEstado estadoAnterior,
                                                SolicitudDesbaneoEstado estadoNuevo,
                                                Long adminId,
                                                String resolucionMotivo) {
        if (entity == null || entity.getId() == null || estadoNuevo == null) {
            return;
        }
        if (estadoAnterior == estadoNuevo) {
            LOGGER.info("[ADMIN][REPORT_HISTORY] requestId={} solicitudId={} action=CAMBIO_ESTADO estadoAnterior={} estadoNuevo={} created=false motivo=same-state",
                    requestId, entity.getId(), estadoAnterior, estadoNuevo);
            return;
        }
        try {
            SolicitudReporteHistorialEntity last = solicitudReporteHistorialRepository.findTopBySolicitudIdOrderByCreatedAtDesc(entity.getId());
            if (last != null
                    && ACTION_CAMBIO_ESTADO.equals(last.getAccion())
                    && last.getEstadoNuevo() == estadoNuevo
                    && Objects.equals(trimToNullable(last.getResolucionMotivo(), MAX_REASON_LENGTH), trimToNullable(resolucionMotivo, MAX_REASON_LENGTH))
                    && Objects.equals(last.getAdminId(), adminId)) {
                LOGGER.info("[ADMIN][REPORT_HISTORY] requestId={} solicitudId={} action=CAMBIO_ESTADO estadoAnterior={} estadoNuevo={} created=false motivo=duplicate-last",
                        requestId, entity.getId(), estadoAnterior, estadoNuevo);
                return;
            }

            SolicitudReporteHistorialEntity historial = new SolicitudReporteHistorialEntity();
            historial.setSolicitudId(entity.getId());
            historial.setTipoReporte(entity.getTipoReporte());
            historial.setEstadoAnterior(estadoAnterior);
            historial.setEstadoNuevo(estadoNuevo);
            historial.setMotivoSnapshot(trimToNullable(entity.getMotivo(), MAX_REASON_LENGTH));
            historial.setResolucionMotivo(trimToNullable(resolucionMotivo, MAX_REASON_LENGTH));
            historial.setUsuarioId(entity.getUsuarioId());
            historial.setAdminId(adminId);
            historial.setAccion(ACTION_CAMBIO_ESTADO);
            historial.setCreatedAt(entity.getUpdatedAt() == null ? LocalDateTime.now() : entity.getUpdatedAt());
            SolicitudReporteHistorialEntity saved = solicitudReporteHistorialRepository.save(historial);
            LOGGER.info("[ADMIN][REPORT_HISTORY] requestId={} solicitudId={} action=CAMBIO_ESTADO estadoAnterior={} estadoNuevo={} created=true historialId={}",
                    requestId, entity.getId(), estadoAnterior, estadoNuevo, saved.getId());
        } catch (RuntimeException ex) {
            LOGGER.warn("[ADMIN][REPORT_HISTORY] requestId={} solicitudId={} created=false error={}",
                    requestId, entity.getId(), safeAuditValue(ex.getMessage()));
        }
    }

